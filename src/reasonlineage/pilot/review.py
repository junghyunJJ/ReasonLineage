"""Anonymous expert material and independent assessments, outside generation."""

import hashlib
import random
import re
import secrets
from pathlib import Path

from .run import save_json

RATINGS = ('grounding', 'causal_rigor', 'specificity', 'testability', 'feasibility')
_IDENTITY = re.compile(r'\b(?:reasonlineage|gpt-6[\w.-]*|claude-opus[\w.-]*|grok-4[\w.-]*|glm-5[\w.-]*|deepseek-v4[\w.-]*)\b', re.I)
_DISCLOSURE = re.compile(
    r'\b(?:as|i am|i\x27m|generated by|written by|my model is)\s+(?:an?\s+)?(?:gpt|claude|opus|grok|glm|deepseek)\b|'
    r'\b(?:this|my|our|the)\s+(?:final|initial|previous|original|revised)\s+(?:revision|proposal|answer|draft|iteration|version)\b|'
    r'\b(?:in|after|during)\s+(?:generation|iteration|round)\s*\d+\b', re.I)


def export_expert(destination, statuses, evidence):
    destination = Path(destination)
    expert = destination / 'expert'
    expert.mkdir(parents=True, exist_ok=False)
    analyst = destination / 'analyst'
    analyst.mkdir(parents=True, exist_ok=False)
    mapping, excluded, proposals, known, lookup = [], [], [], {}, {}
    for status in statuses:
        if status['status'] != 'completed':
            continue
        case, method = status['header']['case'], status['header']['method']
        for stage in ('initial', 'final'):
            proposal = status[stage]
            answer = proposal['answer']
            text = answer['answer'].strip()
            title = answer['ranking'][0]['item'].strip()
            if _IDENTITY.search(text + '\n' + title) or _DISCLOSURE.search(text + '\n' + title):
                excluded.append({'case': case, 'method': method, 'stage': stage, 'reason': 'explicit identity or stage disclosure'})
                continue
            digest = hashlib.sha256((' '.join(text.split())).encode()).hexdigest()
            key = case, digest
            if key not in known:
                pid = 'P' + secrets.token_hex(5)
                known[key] = pid
                proposals.append({'id': pid, 'case': case, 'title': title, 'text': text})
                (expert / f'{pid}.md').write_text(f'# {pid}\n\n{text}\n', encoding='utf-8')
            pid = known[key]
            lookup[case, method, stage] = pid
            mapping.append({'id': pid, 'case': case, 'method': method, 'stage': stage,
                            'candidate': proposal['id'], 'content_sha256': digest})
    pairs, pair_mapping = [], []
    cases = sorted({s['header']['case'] for s in statuses})

    def add_pair(case, first, second, kind, method):
        if first is None or second is None or first == second:
            return
        left, right = random.SystemRandom().sample([first, second], 2)
        pair_id = 'C' + secrets.token_hex(5)
        pairs.append({'id': pair_id, 'case': case, 'left': left, 'right': right})
        pair_mapping.append({'id': pair_id, 'case': case, 'kind': kind, 'method': method,
                             'first': first, 'second': second})

    for case in cases:
        multi = lookup.get((case, 'reasonlineage', 'final'))
        for method in ('gpt', 'opus', 'grok', 'glm'):
            add_pair(case, multi, lookup.get((case, method, 'final')), 'primary', method)
        for method in ('reasonlineage', 'gpt', 'opus', 'grok', 'glm'):
            add_pair(case, lookup.get((case, method, 'initial')), lookup.get((case, method, 'final')), 'secondary', method)
    random.SystemRandom().shuffle(proposals)
    random.SystemRandom().shuffle(pairs)
    # The complete comparison graph has an identifiable multi-model hub.
    # Elicit a blinded overall order; derive planned pair preferences privately.
    packet = {'proposals': proposals, 'pairs': []}
    save_json(expert / 'packet.json', packet)
    save_json(expert / 'ratings.json', {'ratings': [{'id': p['id'], **dict.fromkeys(RATINGS),
                                                  'novelty_note': '', 'reason': '', 'possible_unblinding': ''}
                                                 for p in proposals],
                                       'overall_ordering': [{'case': case, 'tie_groups': [], 'unrankable_ids': [],
                                                             'reason': ''} for case in cases]})
    for case, text in evidence.items():
        (expert / f'{case}-evidence.md').write_text(text, encoding='utf-8')
    (expert / 'README.md').write_text('Review each anonymous proposal against the common case evidence. '
                                    'Rate grounding, causal rigor, specificity, testability and feasibility from 1 (major defects) '
                                    'to 5 (unusually strong). Novelty is descriptive. Within each case list proposal IDs in tie_groups '
                                    'from strongest to weakest: each group contains tied IDs. Put unassessable IDs in unrankable_ids. '
                                    'Explain the key scientific reasons. Record possible unblinding or expertise limitations. '
                                    'Fill ratings.json or a separate table using these IDs.\n', encoding='utf-8')
    save_json(analyst / 'mapping.json', {'proposals': mapping, 'pairs': pair_mapping, 'excluded': excluded})
    return packet


def review_schema(ids):
    properties = {key: {'type': 'integer', 'minimum': 1, 'maximum': 5} for key in RATINGS}
    properties.update(id={'type': 'string', 'enum': list(ids)}, novelty_note={'type': 'string'}, reason={'type': 'string'})
    return {'type': 'object', 'properties': {'reviews': {'type': 'array', 'minItems': len(ids), 'maxItems': len(ids),
             'items': {'type': 'object', 'properties': properties, 'required': list(properties), 'additionalProperties': False}}},
            'required': ['reviews'], 'additionalProperties': False}


def validate_review(data, ids):
    if not isinstance(data, dict) or not isinstance(data.get('reviews'), list):
        raise ValueError('review requires a reviews list')
    items = data['reviews']
    if len(items) != len(ids) or {item.get('id') for item in items if isinstance(item, dict)} != set(ids):
        raise ValueError('review IDs must match each proposal exactly once')
    for item in items:
        for key in RATINGS:
            score = item.get(key)
            if not isinstance(score, int) or isinstance(score, bool) or not 1 <= score <= 5:
                raise ValueError('review rating must be an integer in 1–5')
        if not all(isinstance(item.get(key), str) for key in ('novelty_note', 'reason')):
            raise ValueError('review requires public reason and novelty note')
    return data


def citation_audit(text, pmids, evidence):
    packet_pmids = set(re.findall(r'PMID:\s*`?(\d+)', evidence))
    labels = set(re.findall(r'\bS[1-4]\b', evidence))
    mentioned = set(re.findall(r'\[\s*(S\d+)\s*\]', text))
    cited_pmids = set(pmids) | set(re.findall(r'PMID\s*[:#]?\s*(\d+)', text, re.I))
    dois = sorted(set(re.findall(r'10\.\d{4,9}/[\w./()-]+', text)))
    return {'source_labels': sorted(mentioned), 'unknown_source_labels': sorted(mentioned - labels),
            'pmids': sorted(cited_pmids), 'packet_pmids': sorted(cited_pmids & packet_pmids),
            'outside_packet_pmids': sorted(cited_pmids - packet_pmids), 'dois': dois,
            'packet_metadata': 'preverified primary records; not claim verification',
            'outside_packet_metadata': 'pending' if cited_pmids - packet_pmids or dois else 'not applicable',
            'claim_verification': 'pending', 'approval_indication_verification': 'pending for AML'}


def comparable(multi, solo):
    ratio = None
    eligible = multi['status'] == solo['status'] == 'completed'
    a, b = multi.get('usage', {}), solo.get('usage', {})
    if eligible and not a.get('unknown_usage_calls', 1) and not b.get('unknown_usage_calls', 1) and b.get('reported_tokens', 0) > 0:
        ratio = a['reported_tokens'] / b['reported_tokens']
    return {'token_ratio_multi_over_solo': ratio, 'comparable_usage': ratio is not None and .9 <= ratio <= 1.1,
            'criterion': 'both completed, no unknown usage, total-token ratio 0.9–1.1; not measured FLOPs'}


def derive_preferences(ordering, pairs):
    """Derive the preregistered comparisons without showing their graph."""
    ranks, unavailable = {}, set()
    for case_order in ordering:
        case = case_order['case']
        for rank, group in enumerate(case_order['tie_groups']):
            for pid in group:
                if (case, pid) in ranks:
                    raise ValueError('proposal occurs more than once in expert ordering')
                ranks[case, pid] = rank
        for pid in case_order.get('unrankable_ids', []):
            if (case, pid) in ranks:
                raise ValueError('proposal is both ranked and unrankable')
            unavailable.add((case, pid))
    result = []
    for pair in pairs:
        first, second = (pair['case'], pair['first']), (pair['case'], pair['second'])
        preference = 'unsure'
        if first in ranks and second in ranks and first not in unavailable and second not in unavailable:
            a, b = ranks[first], ranks[second]
            preference = 'tie' if a == b else 'first' if a < b else 'second'
        result.append({**pair, 'preference': preference, 'elicitation': 'blinded overall order'})
    return result
